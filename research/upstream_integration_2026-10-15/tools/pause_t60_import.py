"""Bounded fault injection for a named disposable Launchpad transfer only.

Pause its owned CLI once transfer staging exists; release by creating STATE/release.
The application stays responsive. No UI events are generated by this script.
"""
import argparse
import json
import os
from pathlib import Path
import signal
import subprocess
import time

ROOT = Path(__file__).resolve().parents[3]


def identity(pid):
    return subprocess.check_output(['/bin/ps', '-p', str(pid), '-o', 'lstart=,comm='], text=True).strip()


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--library', type=Path, required=True)
    p.add_argument('--cli', type=Path, required=True)
    p.add_argument('--state', type=Path, required=True)
    p.add_argument('--operation', choices=['import', 'export'], default='import')
    p.add_argument('--output-parent', type=Path)
    args = p.parse_args()
    library = args.library.resolve(strict=True)
    cli = args.cli.resolve(strict=True)
    state = args.state.resolve()
    assert library.is_relative_to(ROOT / '.build/t60-remaining-20261021')
    assert any(cli.is_relative_to(ROOT / name) for name in ('.build/t60-remaining-20261021.app', '.build/t60-remaining-r2-20261021.app', '.build/t60-remaining-r3-20261021.app'))
    assert state.is_relative_to(ROOT / '.build/t60-remaining-20261021') and not state.exists()
    state.mkdir()
    if args.operation == 'export':
        assert args.output_parent is not None
        args.output_parent = args.output_parent.resolve(strict=True)
        assert args.output_parent.is_relative_to(ROOT / '.build/t60-remaining-20261021')
    deadline = time.monotonic() + 90
    while time.monotonic() < deadline:
        rows = subprocess.check_output(['/bin/ps', '-axo', 'pid=,command='], text=True).splitlines()
        matches = [int(row.strip().split(None, 1)[0]) for row in rows
                   if row.strip().split(None, 1)[-1].startswith(str(cli) + ' vm ' + args.operation + ' ')
                   and '--library-root ' + str(library) in row]
        staging = list(library.glob('.import-*/contents/*/Disk.img')) if args.operation == 'import' else list(args.output_parent.glob('.vphone-export-*/output'))
        if len(matches) == 1 and staging:
            pid = matches[0]
            expected = identity(pid)
            os.kill(pid, signal.SIGSTOP)
            record = dict(pid=pid, identity=expected, cli=str(cli), library=str(library), state='paused', operation=args.operation)
            (state / 'paused.json').write_text(json.dumps(record, indent=2) + '\n')
            try:
                end = time.monotonic() + 90
                while not (state / 'release').exists() and time.monotonic() < end:
                    time.sleep(0.1)
            finally:
                try:
                    if identity(pid) == expected:
                        os.kill(pid, signal.SIGCONT)
                        record['state'] = 'resumed'
                except subprocess.CalledProcessError:
                    record['state'] = 'already_exited'
                (state / 'result.json').write_text(json.dumps(record, indent=2) + '\n')
            return
        time.sleep(0.02)
    raise RuntimeError('no owned active transfer observed within deadline')


if __name__ == '__main__':
    main()
