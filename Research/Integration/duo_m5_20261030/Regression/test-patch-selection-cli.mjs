import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const [cliArg,outArg]=process.argv.slice(2);
if(!cliArg||!outArg)throw Error('Usage: node test-patch-selection-cli.mjs <vphone-cli> <new output directory>');
const cli=path.resolve(cliArg),out=path.resolve(outArg);
if(fs.existsSync(out))throw Error('Output must be a new directory');
fs.mkdirSync(out,{recursive:true});
const run=args=>execFileSync(cli,args,{encoding:'utf8'});
const legacy='system-accessibilitybundles-cfw-arm64e_x1',residual=legacy+'_remaining';
const child='system-uikitpopaccessibility-cfw-arm64e_x1';
function exported(name,extra){const target=out+'/'+name+'.plist';run(['fw','export-preset','--output',target,...extra]);return target;}
function report(preset){return JSON.parse(run(['fw','patches','--json','--preset',preset]));}
const first=exported('ax-exception',['--preset','standard','--block',legacy,'--allow',child]);
const firstReport=report(first);
const second=exported('ax-roundtrip',['--preset',first]);
const secondReport=report(second);
const states=r=>r.patches.map(x=>[x.identifier,x.inPreset,x.enabled]);
assert.deepEqual(states(firstReport),states(secondReport));
const ax=firstReport.patches.filter(x=>x.target.startsWith('/System/Library/AccessibilityBundles/'));
assert.equal(ax.length,36);
assert.deepEqual(ax.filter(x=>x.enabled).map(x=>x.identifier),[child]);
assert.equal(firstReport.patches.find(x=>x.identifier===residual).enabled,false);
const residualOnly=report(exported('residual-only',['--preset','standard','--block',residual]));
assert.equal(residualOnly.patches.filter(x=>x.target.startsWith('/System/Library/AccessibilityBundles/')).filter(x=>x.enabled).length,36);
const txm=report(exported('legacy-txm',['--preset','standard','--allow','txm-boot-precheck_admission']));
assert.equal(txm.patches.find(x=>x.identifier==='txm-exp-precheck_admission').enabled,true);
assert.equal(txm.patches.find(x=>x.identifier==='txm-cfw-executable_remap').enabled,true);
const library=out+'/machines',machine=library+'/selection-fixture';
fs.mkdirSync(machine,{recursive:true});
run(['vm','write-manifest','--vm-dir',machine]);
run(['fw','set-patches','selection-fixture','-l',library,'--preset','standard','--block',legacy,'--allow',child]);
const machineReport=JSON.parse(run(['fw','patches','selection-fixture','-l',library,'--json']));
assert.deepEqual(machineReport.allowedPatches,[]);
assert(!machineReport.blockedPatches.includes(legacy));
assert(!machineReport.blockedPatches.includes(child));
assert(machineReport.blockedPatches.includes(residual));
assert.equal(machineReport.patches.filter(x=>x.target.startsWith('/System/Library/AccessibilityBundles/')&&x.enabled).length,1);
run(['fw','set-patches','selection-fixture','-l',library,'--preset','standard','--block','txm-cfw-executable_remap','--allow','txm-boot-precheck_admission']);
const txmMachine=JSON.parse(run(['fw','patches','selection-fixture','-l',library,'--json']));
assert.deepEqual(txmMachine.allowedPatches,['txm-exp-precheck_admission']);
assert.deepEqual(txmMachine.blockedPatches,['txm-cfw-executable_remap']);
fs.writeFileSync(out+'/reports.json',JSON.stringify({first:firstReport,roundtrip:secondReport,residualOnly,txm,machineReport,txmMachine},null,2)+'\n');
console.log('CLI selection: aggregate exception, export round trip, independent residual, legacy TXM alias and stored VM overrides passed');
