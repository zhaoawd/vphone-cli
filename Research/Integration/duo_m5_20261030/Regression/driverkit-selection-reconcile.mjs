// Align this test VM's requested DriverKit policy with its verified live repair.
// This uses the public selection command; it never rewrites plan/receipt files.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync,spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const root=fs.realpathSync(new URL('../../../../',import.meta.url));
const [outArg,auditArg]=process.argv.slice(2),out=path.resolve(outArg),audit=JSON.parse(fs.readFileSync(auditArg));
assert(out.startsWith(root+'/.build/'));assert.equal(audit.live.driverkit.hex,'01000000');assert.equal(audit.live.driverkit.flags,0);
assert.equal(audit.backup.driverkit,null);fs.mkdirSync(out);
const machine=root+'/.build/duo-runtime-84e3ce54/machines/duo-overall-20261116';
const bundle=root+'/.build/overall-port-20261116/REVIEWED/VPhone.bundle',cli=bundle+'/Contents/MacOS/vphone-cli';
const handles=spawnSync('/usr/sbin/lsof',[machine+'/Disk.img',machine+'/nvram.bin',machine+'/SEPStorage'],{encoding:'utf8'});
fs.writeFileSync(out+'/handles.txt',handles.stdout+handles.stderr);assert.equal(handles.status,1,'The VM must be stopped');assert.equal(handles.stdout,'');
const hash=b=>createHash('sha256').update(b).digest('hex');
const files=['PatchSelection.plist','PatchPlan.plist','PatchReceipt.plist'];
const beforeFiles=Object.fromEntries(files.map(name=>{const b=fs.readFileSync(machine+'/'+name);fs.writeFileSync(out+'/'+name+'.before',b);return [name,hash(b)];}));
const patches=()=>JSON.parse(execFileSync(cli,['fw','patches','duo-overall-20261116','-l',path.dirname(machine),'--json'],{encoding:'utf8'}));
const save=(n,v)=>fs.writeFileSync(out+'/'+n+'.json',JSON.stringify(v,null,2)+'\n');
const before=patches();save('before',before);const id='devicetree-cfw-virtual_usb_driverkit';
const tree=before.patches.find(x=>x.identifier===id),repair=before.patches.find(x=>x.identifier==='preboot-cfw-devicetree_virtual_usb_driverkit');
assert.equal(tree.enabled,false);assert.equal(tree.applied,true);assert.equal(tree.pending,true);
assert.equal(repair.enabled,true);assert.equal(repair.applied,true);assert.equal(repair.pending,false);
const selection=JSON.parse(execFileSync('/usr/bin/plutil',['-convert','json','-o','-',machine+'/PatchSelection.plist'],{encoding:'utf8'}));
assert.equal(selection.Preset,'standard');assert.deepEqual(selection.AllowedPatches,[]);
assert.deepEqual(selection.BlockedPatches.toSorted(),[id,'devicetree-cfw-homeview_touch','kernel-cfw-paravirt_gles_renderer'].toSorted());
const args=['fw','set-patches','duo-overall-20261116','-l',path.dirname(machine),'--preset',selection.Preset];
for(const block of selection.BlockedPatches.filter(x=>x!==id))args.push('--block',block);
fs.writeFileSync(out+'/command.json',JSON.stringify({cli,args},null,2));
fs.writeFileSync(out+'/command.stdout',execFileSync(cli,args,{encoding:'utf8'}));
const after=patches();save('after',after);const current=after.patches.find(x=>x.identifier===id);
assert.equal(current.enabled,true);assert.equal(current.applied,true);assert.equal(current.pending,false);
assert.equal(current.planned,tree.planned);
for(const patch of before.patches.filter(x=>x.identifier!==id))assert.deepEqual(after.patches.find(x=>x.identifier===patch.identifier),patch);
const afterFiles=Object.fromEntries(files.map(name=>{const b=fs.readFileSync(machine+'/'+name);fs.writeFileSync(out+'/'+name+'.after',b);return [name,hash(b)];}));
for(const name of ['PatchPlan.plist','PatchReceipt.plist'])assert.equal(afterFiles[name],beforeFiles[name]);
assert(after.patches.every(x=>!x.pending));
save('summary',{beforeFiles,afterFiles,tree:current,pending:after.patches.filter(x=>x.pending).length,audit});
console.log(JSON.stringify({driverkitEnabled:true,liveRepairPreserved:true,pending:0,planAndReceiptUnchanged:true}));
